# 1. Primitive Data Types

# These are the most basic forms of data. they hold a single value.
# Integer (int): Whole numbers without decimals (e.g., 5, -10).
# Float (float): Numbers with decimal points (e.g., 3.14, 2.0).
# String (str): Sequences of characters enclosed in quotes (e.g., "Hello").
# Boolean (bool): Represents logical values: True or False.

# 2. Non-Primitive (Collection)
# Data TypesThese are objects that can store multiple values or collections of data.

